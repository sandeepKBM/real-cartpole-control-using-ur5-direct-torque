"""Minimal 5x7 bitmap font for burning numbers into rendered frames.

Dependency-free on purpose. Every renderer in this repo runs headless on a
host where adding PIL/cv2 just to draw six lines of text is a new install to
maintain; a hardcoded glyph table is ~60 lines and never breaks.

Only uppercase, digits and a handful of symbols -- enough for a HUD. Unknown
characters render as blank rather than raising, because a HUD must never be
the reason a long render dies.
"""
from __future__ import annotations

import numpy as np

