def draw_text(frame: np.ndarray, text: str, *, x: int, y: int,
              color=(255, 255, 255), scale: int = 2, shadow: bool = True) -> np.ndarray:
    """Draw ``text`` into ``frame`` (H,W,3 uint8) in place, top-left at (x, y).

    ``shadow`` draws a 1px-offset dark copy first so the text stays readable
    over both the light floor and the dark robot -- without it the HUD
    disappears against whatever the camera happens to be looking at.
    """
    h, w = frame.shape[:2]
    if shadow:
        draw_text(frame, text, x=x + scale, y=y + scale, color=(0, 0, 0),
                  scale=scale, shadow=False)
    col = np.asarray(color, dtype=np.uint8)
    cx = x
    for ch in text.upper():
        glyph = _G.get(ch)
        if glyph is not None:
            for r, bits in enumerate(glyph):
                for c in range(5):
                    if bits & (1 << (4 - c)):
                        y0, x0 = y + r * scale, cx + c * scale
                        if 0 <= y0 < h and 0 <= x0 < w:
                            frame[y0:min(y0 + scale, h), x0:min(x0 + scale, w)] = col
        cx += 6 * scale
        if cx >= w:
            break
    return frame
